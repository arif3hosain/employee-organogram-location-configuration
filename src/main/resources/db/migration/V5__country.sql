-- =====================================================================
-- V5: Country becomes its own table (option A).
--
--   country ──< location_type ──< location (self-referencing tree)
--
-- * Each country defines its own location levels (location_type.country_id),
--   e.g. Bangladesh: Division (1) > District (2) > Upazila (3) > Branch / Office (4);
--   India could have State > District > Tehsil > Block > Village.
-- * location has NO country column: a location's country is its type's country,
--   so the country is stored once.
-- * The old "COUNTRY" level and the "Bangladesh" location row are removed:
--   the 8 divisions become the roots of the tree. All other location ids stay
--   the same, so employees and org units keep their locations.
-- * If an employee or org unit still points at the old "Bangladesh" location row,
--   the DELETE below fails on its foreign key and the migration stops, instead
--   of guessing a new location for them.
-- =====================================================================

-- ---------- country --------------------------------------------------
CREATE TABLE country (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso2           VARCHAR(2)   NOT NULL,          -- ISO 3166-1 alpha-2, e.g. BD
    iso3           VARCHAR(3)   NOT NULL,          -- ISO 3166-1 alpha-3, e.g. BGD
    name           VARCHAR(100) NOT NULL,
    currency_code  VARCHAR(3),                     -- ISO 4217, e.g. BDT
    phone_code     VARCHAR(8),                     -- e.g. +880
    status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP,
    CONSTRAINT uk_country_iso2 UNIQUE (iso2),
    CONSTRAINT uk_country_iso3 UNIQUE (iso3),
    CONSTRAINT ck_country_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

INSERT INTO country (iso2, iso3, name, currency_code, phone_code)
VALUES ('BD', 'BGD', 'Bangladesh', 'BDT', '+880');

-- ---------- location types belong to a country ------------------------
ALTER TABLE location_type ADD COLUMN country_id BIGINT;
UPDATE location_type SET country_id = (SELECT id FROM country WHERE iso2 = 'BD');
ALTER TABLE location_type ALTER COLUMN country_id SET NOT NULL;
ALTER TABLE location_type ADD CONSTRAINT fk_location_type_country FOREIGN KEY (country_id) REFERENCES country (id);
CREATE INDEX ix_location_type_country ON location_type (country_id);

-- type codes are unique per country (India may also have a DISTRICT type)
ALTER TABLE location_type DROP CONSTRAINT uk_location_type_code;
ALTER TABLE location_type ADD CONSTRAINT uk_location_type_country_code UNIQUE (country_id, code);

-- ---------- the divisions become the roots -------------------------------
-- 1. drop the "/<bangladeshId>" prefix from every materialized path: "/1/12/45/" -> "/12/45/"
UPDATE location
   SET path = SUBSTRING(path, (SELECT LENGTH(CAST(b.id AS VARCHAR)) FROM location b WHERE b.code = 'BD') + 2)
 WHERE path LIKE (SELECT '/' || CAST(b.id AS VARCHAR) || '/%' FROM location b WHERE b.code = 'BD');

-- 2. children of "Bangladesh" (the divisions) no longer have a parent
UPDATE location SET parent_id = NULL, version = version + 1
 WHERE parent_id = (SELECT b.id FROM location b WHERE b.code = 'BD');

-- 3. remove the "Bangladesh" location row and the COUNTRY level
DELETE FROM location WHERE code = 'BD';
DELETE FROM location_type t
 WHERE t.code = 'COUNTRY'
   AND NOT EXISTS (SELECT 1 FROM location l WHERE l.location_type_id = t.id);

-- 4. renumber Bangladesh's levels so the top level is 1 again:
--    Division 2->1, District 3->2, Upazila 4->3, Branch/Office 5->4 (and any extra types the same way)
UPDATE location_type SET level_no = level_no - 1, version = version + 1
 WHERE country_id = (SELECT id FROM country WHERE iso2 = 'BD')
   AND level_no > 1;
