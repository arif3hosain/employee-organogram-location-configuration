-- =====================================================================
-- V3: Grade becomes its own entity. Designations point to a grade
-- instead of carrying a hand-typed grade_rank number.
-- Written as a new migration (not an edit of V1/V2) so databases that
-- already ran V1/V2 upgrade cleanly.
-- =====================================================================

CREATE TABLE grade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    rank_no     INTEGER      NOT NULL,          -- 1 = most senior
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT uk_grade_code UNIQUE (code),
    CONSTRAINT uk_grade_rank UNIQUE (rank_no),
    CONSTRAINT ck_grade_rank CHECK (rank_no >= 1),
    CONSTRAINT ck_grade_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

