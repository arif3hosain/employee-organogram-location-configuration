-- =====================================================================
-- PMS POC - corehr schema (PostgreSQL)
-- Type-wise location tree, organogram (org units + designations +
-- sanctioned posts) and employee.
-- Also runs on H2 in PostgreSQL mode (tests).
-- =====================================================================

-- ---------- Location: types are data, not tables -------------------
CREATE TABLE location_type (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    level_no    INTEGER      NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT uk_location_type_code UNIQUE (code),
    CONSTRAINT ck_location_type_level CHECK (level_no >= 1),
    CONSTRAINT ck_location_type_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE location (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(30)   NOT NULL,
    name              VARCHAR(150)  NOT NULL,
    location_type_id  BIGINT        NOT NULL,
    parent_id         BIGINT,
    path              VARCHAR(1000),
    status            VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP,
    CONSTRAINT uk_location_code UNIQUE (code),
    CONSTRAINT fk_location_type FOREIGN KEY (location_type_id) REFERENCES location_type (id),
    CONSTRAINT fk_location_parent FOREIGN KEY (parent_id) REFERENCES location (id),
    CONSTRAINT ck_location_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_location_parent ON location (parent_id);
CREATE INDEX ix_location_type ON location (location_type_id);
CREATE INDEX ix_location_path ON location (path);

-- ---------- Organogram ---------------------------------------------
CREATE TABLE org_unit_type (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    level_no    INTEGER      NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT uk_org_unit_type_code UNIQUE (code),
    CONSTRAINT ck_org_unit_type_level CHECK (level_no >= 1),
    CONSTRAINT ck_org_unit_type_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE org_unit (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(30)   NOT NULL,
    name              VARCHAR(150)  NOT NULL,
    org_unit_type_id  BIGINT        NOT NULL,
    nature            VARCHAR(20),
    parent_id         BIGINT,
    location_id       BIGINT,
    path              VARCHAR(1000),
    sort_order        INTEGER,
    status            VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP,
    CONSTRAINT uk_org_unit_code UNIQUE (code),
    CONSTRAINT fk_org_unit_type FOREIGN KEY (org_unit_type_id) REFERENCES org_unit_type (id),
    CONSTRAINT fk_org_unit_parent FOREIGN KEY (parent_id) REFERENCES org_unit (id),
    CONSTRAINT fk_org_unit_location FOREIGN KEY (location_id) REFERENCES location (id),
    CONSTRAINT ck_org_unit_nature CHECK (nature IS NULL OR nature IN ('FUNCTIONAL', 'NON_FUNCTIONAL')),
    CONSTRAINT ck_org_unit_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_org_unit_parent ON org_unit (parent_id);
CREATE INDEX ix_org_unit_path ON org_unit (path);

CREATE TABLE designation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    grade_rank  INTEGER      NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT uk_designation_code UNIQUE (code),
    CONSTRAINT ck_designation_rank CHECK (grade_rank >= 1),
    CONSTRAINT ck_designation_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- Sanctioned posts: how many of each designation a unit may have
CREATE TABLE org_unit_post (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_unit_id       BIGINT     NOT NULL,
    designation_id    BIGINT     NOT NULL,
    sanctioned_count  INTEGER    NOT NULL,
    version           BIGINT     NOT NULL DEFAULT 0,
    created_at        TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP,
    CONSTRAINT uk_org_unit_post UNIQUE (org_unit_id, designation_id),
    CONSTRAINT fk_org_unit_post_unit FOREIGN KEY (org_unit_id) REFERENCES org_unit (id),
    CONSTRAINT fk_org_unit_post_desig FOREIGN KEY (designation_id) REFERENCES designation (id),
    CONSTRAINT ck_org_unit_post_count CHECK (sanctioned_count >= 0)
);

-- ---------- Employee ------------------------------------------------
CREATE TABLE employee (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code   VARCHAR(30)   NOT NULL,
    full_name       VARCHAR(150)  NOT NULL,
    email           VARCHAR(150)  NOT NULL,
    phone           VARCHAR(30),
    join_date       DATE          NOT NULL,
    designation_id  BIGINT        NOT NULL,
    org_unit_id     BIGINT        NOT NULL,
    location_id     BIGINT        NOT NULL,
    supervisor_id   BIGINT,
    status          VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    version         BIGINT        NOT NULL DEFAULT 0,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT uk_employee_code UNIQUE (employee_code),
    CONSTRAINT uk_employee_email UNIQUE (email),
    CONSTRAINT fk_employee_designation FOREIGN KEY (designation_id) REFERENCES designation (id),
    CONSTRAINT fk_employee_org_unit FOREIGN KEY (org_unit_id) REFERENCES org_unit (id),
    CONSTRAINT fk_employee_location FOREIGN KEY (location_id) REFERENCES location (id),
    CONSTRAINT fk_employee_supervisor FOREIGN KEY (supervisor_id) REFERENCES employee (id),
    CONSTRAINT ck_employee_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_employee_org_unit ON employee (org_unit_id);
CREATE INDEX ix_employee_location ON employee (location_id);
CREATE INDEX ix_employee_supervisor ON employee (supervisor_id);
CREATE INDEX ix_employee_designation ON employee (designation_id);
