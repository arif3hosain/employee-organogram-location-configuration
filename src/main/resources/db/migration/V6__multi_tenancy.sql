-- =====================================================================
-- V6: Multi-tenancy (shared database, shared schema, tenant column).
--
-- Rule: only PARENT tables (aggregate roots, which are listed, searched or
-- referenced on their own) carry tenant_id. CHILD tables have no tenant
-- column: a child row belongs to the tenant of its parent row and is only
-- reached through that parent. SHARED tables (reference data that is the same
-- for every customer) have no tenant column at all.
--
--   SHARED  : tenant, country
--   PARENT  : location_type, location, org_unit_type, org_unit,
--             grade, designation, employee                (get tenant_id)
--   CHILD   : org_unit_post -> org_unit                   (no tenant_id)
--
-- Every existing row goes to tenant 1 (the current organisation), so ids are
-- unchanged. IDs stay globally unique (one identity per table), which keeps
-- legacy ERP ids usable as-is for tenant 1.
--
-- Safety in the database itself, not only in Java:
--   * codes are unique per tenant: (tenant_id, code)
--   * parent-to-parent FKs are composite (tenant_id, x_id) -> (tenant_id, id),
--     so a row can never point to another tenant's row
--   * tenant_id has no default: every insert must say which tenant it is for
-- =====================================================================

CREATE TABLE tenant (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(150) NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT uk_tenant_code UNIQUE (code),
    CONSTRAINT ck_tenant_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

